import test from 'node:test';
import assert from 'node:assert/strict';
import * as m from '../src/model.js';

test('pause, UTC rollover, bounded frames, manual time and reset use one authoritative clock', () => {
  assert.equal(typeof m.advance, 'function', 'authoritative playback exists');
  const s = m.createSimulation({ reducedMotion: true });
  assert.equal(s.paused, true);
  assert.equal(s.flocks.length, 3);
  const initial = structuredClone(s);
  m.advance(s, 99);
  assert.deepEqual(s, initial);
  const born = m.spawnFlock(s, { species: 'common-starling', count: 5, lat: -90, lon: -180 });
  m.advance(s, .03);
  assert.equal(s.paused, true);
  assert.equal(born.birds.length, 5);
  assert.equal(s.time, initial.time);
  m.setTime(s, Date.parse('2026-12-31T23:59:50Z'));
  const frozen = structuredClone(s.flocks);
  m.advance(s, .05);
  assert.deepEqual(s.flocks, frozen);
  s.paused = false;
  m.advance(s, .05);
  assert.equal(new Date(s.time).toISOString(), '2027-01-01T00:00:20.000Z');
  const before = s.time;
  m.advance(s, 3600);
  assert.equal(s.time - before, 30000);
  m.advance(s, NaN);
  m.advance(s, -2);
  assert.equal(s.time - before, 30000);
  assert.throws(() => m.setTime(s, NaN), RangeError);
  s.speed = 4;
  s.behavior.cohesion = 2;
  m.resetSimulation(s);
  assert.deepEqual(s, initial);
  const normal = m.createSimulation();
  assert.equal(normal.paused, false);
  normal.time = Date.parse('2028-02-28T23:59:50Z');
  m.advance(normal, .05);
  assert.equal(new Date(normal.time).toISOString(), '2028-02-29T00:00:20.000Z');
});
